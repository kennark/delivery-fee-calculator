create table regional_base_fee_rules (
 city tinyint check ((city between 0 and 2)),
 fee float(53) not null,
 vehicle_type tinyint check ((vehicle_type between 0 and 2)),
 id bigint generated by default as identity,
 primary key (id)
);

create table weather_condition_fee_rules (
 fee float(53) not null,
 max_value float(53),
 min_value float(53),
 type tinyint check ((type between 0 and 2)),
 id bigint generated by default as identity,
 string_value varchar(255),
 primary key (id)
);